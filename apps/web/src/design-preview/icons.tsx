const DEFAULT_ICON_SIZE = 22;
export function DesignIcon({
  name,
  size = DEFAULT_ICON_SIZE,
}: {
  name: IconName;
  size?: number;
}): React.JSX.Element {
  const IconComponent = ICONS[name];
  return <IconComponent size={size} weight="regular" aria-hidden="true" />;
}
